/**
 * npm run eval -- [--llm] [--runs N] [EXC-2001 ...]
 * Writes docs/results/eval-report{-llm}.md. NOTE: resets the target database per run.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pool } from '../src/db/pool.js';
import { ensureSeeded } from '../src/db/reset.js';
import { runEvaluation } from '../src/eval/harness.js';

const args = process.argv.slice(2);
const mode = args.includes('--llm') ? 'llm' : 'deterministic';
const ri = args.indexOf('--runs');
const repetitions = ri >= 0 ? Number(args[ri + 1]) : mode === 'llm' ? 2 : 3;
const exceptions = args.filter((a) => /^EXC-\d{4}$/.test(a));

await ensureSeeded();
const s = await runEvaluation({ mode, repetitions, exceptions, onProgress: (m) => console.log(m) });
const md = [
  `# Resolver evaluation (${mode}${s.model ? `, ${s.model}` : ''})`, '',
  `Batch \`${s.batch_id}\` · ${s.runs} runs (${s.repetitions} repetition(s) × ${s.by_exception.length} seeded exceptions) · each run starts from a clean reset. Generated by \`npm run eval${mode === 'llm' ? ' -- --llm' : ''}\`.`, '',
  '| Metric | Value |', '|---|---|',
  `| Outcome accuracy vs ground truth | ${s.accuracy_pct}% |`,
  `| Consistency (same outcome across repetitions) | ${s.consistency_pct}% of exceptions |`,
  `| LLM proposal = final decision (agreement) | ${s.llm_agreement_pct ?? 'n/a'}${s.llm_agreement_pct !== null ? '%' : ''} |`,
  `| Guard overrides | ${s.guard_override_pct}% of runs |`,
  `| LLM fallbacks | ${s.fallback_pct}% of runs |`,
  `| Unsafe actions executed | ${s.unsafe_actions} |`,
  `| Avg tool calls / run | ${s.avg_tool_calls} |`,
  `| Avg latency / run | ${s.avg_ms} ms |`, '',
  '| Exception | Expected | Outcomes | Accuracy | Consistent | Agreement | Overrides | Avg tools | Avg ms | Fallbacks |', '|---|---|---|---|---|---|---|---|---|---|',
  ...s.by_exception.map((e) => `| ${e.exception_id} | ${e.expected} | ${Object.entries(e.outcomes).map(([k, v]) => `${k}×${v}`).join(', ')} | ${e.accuracy_pct}% | ${e.consistent ? 'yes' : 'no'} | ${e.agreement_pct ?? 'n/a'} | ${e.overrides} | ${e.avg_tool_calls} | ${e.avg_ms} | ${e.fallbacks} |`),
  '', 'Interpretation: accuracy measures the *final* (guarded) outcome; agreement measures how often the model\'s own proposal already matched it. Overrides show the guard correcting the model — accuracy stays high even when agreement is lower, which is the point of the design.', '',
].join('\n');
const dir = join(import.meta.dirname, '../../docs/results');
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, `eval-report${mode === 'llm' ? '-llm' : ''}.md`), md);
console.log(md);
await pool.end();
